"""Embeds effects.json into Sources/G5Core/EffectsData.swift as a Swift string.
Usage: python3 tools/embed_catalog.py [effects.json] [EffectsData.swift]"""
import sys, json
src = sys.argv[1] if len(sys.argv) > 1 else "Sources/G5Core/Resources/effects.json"
dst = sys.argv[2] if len(sys.argv) > 2 else "Sources/G5Core/EffectsData.swift"
data = json.dumps(json.load(open(src)), ensure_ascii=False, separators=(",", ":"))
open(dst, "w").write('// Generated by tools/make_catalog.py — do not edit.\nlet effectsJSON = ##"""\n' + data + '\n"""##\n')
